
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using StudentManagementAPI.Data;
using StudentManagementAPI.Models;

namespace StudentManagementAPI.Controllers
{
    [ApiController]
    [Route("api/[controller]")]
    public class StudentsController : ControllerBase
    {
        // Database context
        private readonly AppDbContext _context;

        // Dependency Injection
        public StudentsController(AppDbContext context)
        {
            _context = context;
        }

        // GET: api/students
        [HttpGet]
        public async Task<ActionResult<IEnumerable<Student>>>
            GetAll()
        {
            var students = await _context.Students
                .AsNoTracking()
                .ToListAsync();

            return Ok(students);
        }

        // GET: api/students/1
        [HttpGet("{id:int}")]
        public async Task<ActionResult<Student>>
            GetById(int id)
        {
            var student = await _context.Students
                .AsNoTracking()
                .FirstOrDefaultAsync(s => s.Id == id);

            if (student == null)
            {
                return NotFound(new
                {
                    message = $"Student with ID {id} not found."
                });
            }

            return Ok(student);
        }

        [HttpPost]
        public async Task<ActionResult<Student>> Create(
            Student student)
        {
            // Check duplicate student code or email
            bool exists = await _context.Students.AnyAsync(s =>
                s.StudentCode == student.StudentCode ||
                s.Email == student.Email);

            if (exists)
            {
                return Conflict(new
                {
                    message = "Student code or email already exists."
                });
            }

            // ID is generated by SQL Server
            student.Id = 0;

            _context.Students.Add(student);

            await _context.SaveChangesAsync();

            return CreatedAtAction(
                nameof(GetById),
                new { id = student.Id },
                student);
        }

        [HttpPut("{id:int}")]
        public async Task<IActionResult> Update(
            int id, Student updatedStudent)
        {
            var student = await _context.Students
                .FindAsync(id);

            if (student == null)
            {
                return NotFound(new
                {
                    message = $"Student with ID {id} not found."
                });
            }

            // Check duplicates belonging to other students
            bool duplicate = await _context.Students
                .AnyAsync(s =>
                    s.Id != id &&
                    (s.StudentCode == updatedStudent.StudentCode ||
                     s.Email == updatedStudent.Email));

            if (duplicate)
            {
                return Conflict(new
                {
                    message = "Student code or email already exists."
                });
            }

            student.StudentCode = updatedStudent.StudentCode;
            student.FullName = updatedStudent.FullName;
            student.Age = updatedStudent.Age;
            student.Email = updatedStudent.Email;
            student.Major = updatedStudent.Major;
            student.GPA = updatedStudent.GPA;

            await _context.SaveChangesAsync();

            return NoContent();
        }


        [HttpDelete("{id:int}")]
        public async Task<IActionResult> Delete(int id)
        {
            var student = await _context.Students.FindAsync(id);

            if (student == null)
            {
                return NotFound(new
                {
                    message = $"Student with ID {id} not found."
                });
            }

            _context.Students.Remove(student);

            await _context.SaveChangesAsync();

            return NoContent();
        }



    }
}
